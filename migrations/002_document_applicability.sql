-- Применимость на уровне ДОКУМЕНТА.
--
-- Зачем. Строка «Применимо к: …» в ответе собирается механически из метаданных,
-- а не просьбой к модели её вспомнить. Но у чанка эти метаданные есть редко
-- и по делу: из 164 чанков SEBU7844-37 разметку несут 13. Это не пробел
-- разметки — большинство процедур применимо ко всему семейству и потому
-- ничего не перечисляет. Процедуре очистки охладителя незачем называть шесть
-- моделей: она одна на все.
--
-- Значит применимость по умолчанию задаёт документ, а метаданные чанка её
-- СУЖАЮТ. Разрешение — в rag/generator.py, applicability_line():
--     control_module чанка      → «двигатели с ADEM II»
--     иначе applicable_models чанка → перечислить их
--     иначе applicable_models документа → перечислить их
--
-- Источник — титульная страница. У SEBU7844-37 там 50 строк вида
-- «S2D 1-UP (3508B)»: 50 серийных префиксов и 6 моделей. Разбор —
-- ingestion/pipeline.py, parse_title_page().
--
-- serial_prefixes сейчас не используется в ответе и лежит про запас: механик
-- читает применимость по табличке на двигателе, а там серийный номер, а не
-- название модели. Понадобится на этапе 4 — «ваш S2D? это 3508B».

ALTER TABLE documents
    ADD COLUMN IF NOT EXISTS applicable_models TEXT[] NOT NULL DEFAULT '{}',
    ADD COLUMN IF NOT EXISTS serial_prefixes   TEXT[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN documents.applicable_models IS
    'Модели двигателей с титульной страницы: 3508B, 3512B, 3516B, 3508C, … '
    'Применимость ПО УМОЛЧАНИЮ: используется, когда чанк не сузил её сам.';

COMMENT ON COLUMN documents.serial_prefixes IS
    'Серийные префиксы с титула: S2D, PXW, MB2, … Резерв этапа 4: на двигателе '
    'написан серийный номер, а не модель.';
